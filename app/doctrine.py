"""Generate the producer skill's contracts from their Python sources."""
import json
from dataclasses import fields
from pathlib import Path

from . import storyboard
from .schema import FrameSpec

REFERENCES = Path(__file__).resolve().parents[1] / '.claude/skills/corkbored-producer/references'
HEADER = 'Generated by `cli doctrine --write`; do not edit\n\n'


def motion():
    lines = [HEADER.rstrip(), '', '# FrameSpec defaults']
    spec = FrameSpec()
    group = None
    for field in fields(FrameSpec):
        current = field.metadata['group']
        if current != group:
            lines += ['', f'## {current}', '', '| Field | Default |', '| --- | --- |']
            group = current
        value = json.dumps(getattr(spec, field.name), ensure_ascii=False).replace('|', r'\|')
        lines.append(f'| `{field.name}` | `{value}` |')
    return '\n'.join(lines) + '\n'


def patch():
    return (HEADER + '# Storyboard patch contract\n\n' + storyboard.__doc__.strip() +
            '\n\nEditable fields: ' + ', '.join(f'`{key}`' for key in sorted(storyboard.EDITABLE)) +
            '\n\n' + storyboard.apply.__doc__.strip() + '\n')


def write(path=None):
    if path is not None:
        path.write_text(motion(), encoding='utf-8')
    else:
        REFERENCES.mkdir(parents=True, exist_ok=True)
        (REFERENCES / 'motion.md').write_text(motion(), encoding='utf-8')
        (REFERENCES / 'storyboard.md').write_text(patch(), encoding='utf-8')
