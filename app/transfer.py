"""A project as one file, so it can be carried to another machine.

A `.youslop` file is a zip of the project's own folder plus whatever it leans
on from outside it, so that it opens on the other machine looking the way it
did here:

    youslop.json        what this is, and which project
    project/...         the project folder: script, pictures, takes, settings
    channel/...         its channel, if it has one — minus the YouTube login
    music/<name>        the music bed named by the project or the channel
    style.json          its saved video style, if it uses one

Left out on purpose: the render caches (`segments/`, `titles/`) and the
finished video (`out/`), which can be hundreds of megabytes and are rebuilt by
the next render; and the channel's `youtube.json`, which is a credential and
does not belong in a file someone emails to themselves.

Nothing in project.json is an absolute path — media and takes are stored
relative to the project folder — which is the only reason the folder can be
moved between machines whose data folders live in different places.
"""
from __future__ import annotations

import json
import shutil
import tempfile
import time
import zipfile
from pathlib import Path

from . import channels, slide_styles, store
from .config import CACHE_DIR, CHANNELS_DIR, MUSIC_DIR, PROJECTS_DIR
from .schema import Project, _uid

FORMAT_VERSION = 1
EXTENSION = ".youslop"
MANIFEST = "youslop.json"

# Regenerated by a render; never worth carrying.
_SKIP_PROJECT_DIRS = {"segments", "titles", "out"}
_SKIP_SUFFIXES = {".tmp", ".part"}
_SKIP_CHANNEL_FILES = {"youtube.json"}

# Already compressed: deflating them again costs time and saves nothing.
_STORED = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".mp4", ".mov", ".webm",
           ".mp3", ".m4a", ".aac", ".ogg", ".opus", ".flac"}


class TransferError(ValueError):
    pass


class AlreadyHere(TransferError):
    """The project in the file is already on this machine."""
    def __init__(self, pid: str, title: str):
        super().__init__(f"{title or pid} is already here.")
        self.pid, self.title = pid, title


def filename_for(project) -> str:
    """A filesystem-safe name for the export, from the video's title."""
    name = (project.title or project.idea or project.id)[:60]
    safe = "".join(c if c.isalnum() or c in " -_" else " " for c in name)
    return "-".join(safe.split()).lower() or project.id


def _add_tree(zf: zipfile.ZipFile, root: Path, prefix: str,
              skip_dirs: set[str] = frozenset(),
              skip_files: set[str] = frozenset()) -> None:
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        if rel.parts[0] in skip_dirs or path.name in skip_files:
            continue
        if path.suffix in _SKIP_SUFFIXES or not path.is_file():
            continue
        method = zipfile.ZIP_STORED if path.suffix.lower() in _STORED else zipfile.ZIP_DEFLATED
        zf.write(path, f"{prefix}/{rel.as_posix()}", compress_type=method)


def export(pid: str, dest: Path) -> dict:
    """Write project `pid` to `dest` as a .youslop file. Returns a summary."""
    with store.lock_for(pid):
        p = store.load(pid)
        root = PROJECTS_DIR / pid
        channel = channels.load_or_none(p.channel_id) if p.channel_id else None
        music = {m for m in (p.music, channel.music if channel else "")
                 if m and m != "__auto__" and (MUSIC_DIR / m).is_file()}
        style_id = slide_styles.id_from_format(p.style.format or "")
        style = slide_styles.export_bundle(style_id) if style_id else None

        manifest = {
            "youslop_project": FORMAT_VERSION,
            "project_id": p.id,
            "title": p.title or p.idea[:80],
            "channel_id": channel.id if channel else "",
            "style_id": style_id if style else "",
            "exported_at": time.time(),
        }
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_name(dest.name + ".part")
        try:
            with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
                zf.writestr(MANIFEST, json.dumps(manifest, indent=2))
                _add_tree(zf, root, "project", skip_dirs=_SKIP_PROJECT_DIRS)
                if channel:
                    _add_tree(zf, CHANNELS_DIR / channel.id, "channel",
                              skip_files=_SKIP_CHANNEL_FILES)
                for name in sorted(music):
                    zf.write(MUSIC_DIR / name, f"music/{name}",
                             compress_type=zipfile.ZIP_STORED)
                if style:
                    zf.writestr("style.json", json.dumps(style, indent=2))
            tmp.replace(dest)
        finally:
            tmp.unlink(missing_ok=True)
    return {"path": str(dest), "size_mb": round(dest.stat().st_size / 1e6, 1),
            "title": manifest["title"]}


def _extract(zf: zipfile.ZipFile, prefix: str, into: Path) -> None:
    """Unpack the members under `prefix/` into `into`, refusing any that would
    land outside it (a crafted zip can name `../../somewhere`)."""
    into = into.resolve()
    for info in zf.infolist():
        if info.is_dir() or not info.filename.startswith(prefix + "/"):
            continue
        rel = info.filename[len(prefix) + 1:]
        target = (into / rel).resolve()
        if not target.is_relative_to(into):
            raise TransferError(f"Refusing a file outside the project: {info.filename}")
        target.parent.mkdir(parents=True, exist_ok=True)
        with zf.open(info) as src, target.open("wb") as dst:
            shutil.copyfileobj(src, dst)


def read_manifest(src: Path) -> dict:
    try:
        with zipfile.ZipFile(src) as zf:
            data = json.loads(zf.read(MANIFEST))
    except (zipfile.BadZipFile, KeyError, json.JSONDecodeError):
        raise TransferError("That isn't a Youslop project file.")
    if not isinstance(data, dict) or not data.get("youslop_project"):
        raise TransferError("That isn't a Youslop project file.")
    if int(data["youslop_project"]) > FORMAT_VERSION:
        raise TransferError("That project was saved by a newer Youslop. "
                            "Update this one to open it.")
    return data


def import_(src: Path, on_conflict: str = "") -> dict:
    """Open a .youslop file into this machine's projects.

    `on_conflict` decides what happens when the same project is already here:
    "" raises AlreadyHere so the caller can ask, "replace" overwrites it (the
    usual case when carrying one project back and forth), "copy" keeps both.
    """
    manifest = read_manifest(src)
    old_pid = str(manifest.get("project_id") or "")
    if not old_pid or "/" in old_pid or "\\" in old_pid or old_pid.startswith("."):
        raise TransferError("That project file has no usable id.")

    pid = old_pid
    if store.exists(old_pid):
        if on_conflict == "replace":
            pass
        elif on_conflict == "copy":
            pid = _uid("p")
        else:
            here = store.load(old_pid)
            raise AlreadyHere(old_pid, here.title or here.idea[:80])

    with zipfile.ZipFile(src) as zf:
        names = set(zf.namelist())
        if "project/project.json" not in names:
            raise TransferError("That project file has no project in it.")

        # Unpacked in the cache and moved in whole, so a failure halfway leaves
        # whatever was here before untouched. Not in the projects folder itself:
        # the video list would show the half-unpacked copy as a second project.
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        PROJECTS_DIR.mkdir(parents=True, exist_ok=True)
        staging = Path(tempfile.mkdtemp(prefix="import-", dir=CACHE_DIR))
        try:
            _extract(zf, "project", staging)
            p = Project.from_dict(json.loads(
                (staging / "project.json").read_text(encoding="utf-8")))

            # The finished video was left behind, so the project must not
            # claim to have one.
            if p.render and not (staging / str(p.render.get("output", ""))).is_file():
                p.render = {}
                if p.status == "rendered":
                    p.status = "recording"

            installed = _install_extras(zf, names, manifest, p)

            if pid != old_pid:
                p.title = f"{p.title or p.idea[:60]} (copy)"
            p.id = pid
            (staging / "project.json").write_text(
                json.dumps(p.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8")

            with store.lock_for(pid):
                final = PROJECTS_DIR / pid
                if final.exists():
                    shutil.rmtree(final)
                shutil.move(str(staging), str(final))
        finally:
            shutil.rmtree(staging, ignore_errors=True)

    store.project_dir(pid)      # recreate the render folders left out of the file
    return {"id": pid, "title": p.title or p.idea[:80], **installed}


def _install_extras(zf: zipfile.ZipFile, names: set[str], manifest: dict, p) -> dict:
    """Bring in the channel, music and style the project leans on — each only
    if this machine does not already have its own, which always wins."""
    out = {"channel": "", "music": [], "style": ""}

    cid = p.channel_id
    if cid and channels.load_or_none(cid) is None:
        if (cid == manifest.get("channel_id") and "channel/channel.json" in names
                and "/" not in cid and "\\" not in cid and not cid.startswith(".")):
            _extract(zf, "channel", CHANNELS_DIR / cid)
            out["channel"] = cid
        if channels.load_or_none(cid) is None:
            p.channel_id = ""       # a standalone video, rather than a dangling link

    MUSIC_DIR.mkdir(parents=True, exist_ok=True)
    for name in names:
        if not name.startswith("music/") or name.endswith("/"):
            continue
        track = Path(name).name
        if track and not (MUSIC_DIR / track).exists():
            with zf.open(name) as src, (MUSIC_DIR / track).open("wb") as dst:
                shutil.copyfileobj(src, dst)
            out["music"].append(track)

    style_id = str(manifest.get("style_id") or "")
    if style_id and "style.json" in names and slide_styles.get(style_id) is None:
        bundle = json.loads(zf.read("style.json"))
        # An earlier import of this same file already made it here under a new
        # id; reuse that one rather than filling the picker with duplicates.
        same = next((x for x in slide_styles.list_styles()
                     if (slide_styles.export_bundle(x["id"]) or {}).get("spec") == bundle.get("spec")
                     and x["name"] == bundle.get("name")), None)
        if same is None:
            same = slide_styles.import_bundle(bundle)
            out["style"] = same.get("name", "")
        p.style.format = slide_styles.format_for(same["id"])
    return out
